// Generates Zod schemas and TypeScript API types from the committed JSON Schemas / OpenAPI
// document (which are themselves exported from the pydantic models). Output is committed;
// CI re-runs this and fails on drift.
import $RefParser from "@apidevtools/json-schema-ref-parser";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { jsonSchemaToZod } from "json-schema-to-zod";
import prettier from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "generated");
const banner = "// Generated by scripts/generate.mjs from the pydantic models. Do not edit.\n";

async function format(source, filepath) {
  return prettier.format(source, { filepath, printWidth: 100 });
}

async function write(file, source) {
  await mkdir(out, { recursive: true });
  await writeFile(join(out, file), await format(source, file));
}

const targets = [
  ["workspace.schema.json", "workspace.zod.ts", "workspaceConfigSchema"],
  ["public-config.schema.json", "public-config.zod.ts", "publicWorkspaceConfigSchema"],
  ["lead-submission.schema.json", "lead-submission.zod.ts", "leadSubmissionSchema"],
  ["lead-list.schema.json", "lead-list.zod.ts", "leadListSchema"],
  ["lead-detail.schema.json", "lead-detail.zod.ts", "leadDetailSchema"],
  ["retrigger-result.schema.json", "retrigger-result.zod.ts", "retriggerResultSchema"],
  ["workspace-summaries.schema.json", "workspace-summaries.zod.ts", "workspaceSummariesSchema"],
  ["review-request.schema.json", "review-request.zod.ts", "reviewRequestSchema"],
  ["review-result.schema.json", "review-result.zod.ts", "reviewResultSchema"],
  ["agent-runs.schema.json", "agent-runs.zod.ts", "agentRunsSchema"],
  ["metrics.schema.json", "metrics.zod.ts", "metricsSchema"],
  ["kb-chat-entry.schema.json", "kb-chat-entry.zod.ts", "kbChatEntrySchema"],
  ["kb-chat-entries.schema.json", "kb-chat-entries.zod.ts", "kbChatEntriesSchema"],
];

for (const [input, output, name] of targets) {
  const schema = JSON.parse(await readFile(join(root, "schemas", input), "utf8"));
  const resolved = await $RefParser.dereference(schema);
  delete resolved.$defs;
  const code = jsonSchemaToZod(resolved, { module: "esm", name, type: true, zodVersion: 4 });
  await write(output, banner + code);
}

const openapi = JSON.parse(await readFile(join(root, "openapi.json"), "utf8"));
const ast = await openapiTS(openapi);
await write("api-types.ts", banner + astToString(ast));

await write(
  "index.ts",
  banner +
    targets.map(([, output]) => `export * from "./${output.replace(".ts", "")}";`).join("\n") +
    '\nexport type { components, paths } from "./api-types";\n',
);
console.log("contracts generated");
